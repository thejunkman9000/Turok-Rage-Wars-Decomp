#!/usr/bin/env python3
"""Statically recompile selected functions (MIPS asm -> C) into port/native/recomp/<fn>.c.
usage: python port/gen_recomp.py func_0040FC14 [func_...]       (reads port/recomp.txt too)
The generated files are compiled by build_clang.py like the rest of the game code; a function that is recompiled is excluded
from the m2c fallback (port/m2c_deny.txt is updated)."""
import glob, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mips2c, m2c_fallback

HEADER = '''/* generated by port/gen_recomp.py from the original MIPS code: %s - do not edit */
typedef unsigned int u32; typedef signed int s32; typedef unsigned short u16; typedef signed short s16;
typedef unsigned char u8; typedef signed char s8; typedef unsigned long long u64; typedef long long s64;
extern void *memcpy(void *, const void *, unsigned);
extern float sqrtf(float); extern float fabsf(float); extern double sqrt(double); extern double fabs(double);
extern double floor(double); extern double ceil(double); extern double rint(double); extern float floorf(float); extern float ceilf(float); extern float rintf(float);
static double gd(const float *f, int i) { u32 lo, hi; u64 v; double d; memcpy(&lo, &f[2 * i], 4); memcpy(&hi, &f[2 * i + 1], 4); v = ((u64)hi << 32) | lo; memcpy(&d, &v, 8); return d; }      /* FR=1: register i = words f[2i] (low, also its single view) and f[2i+1] (high); word-sized accesses only, the big-endian rewrite swaps every load/store */
static void sd(float *f, int i, double d) { u64 v; u32 lo, hi; memcpy(&v, &d, 8); lo = (u32)v; hi = (u32)(v >> 32); memcpy(&f[2 * i], &lo, 4); memcpy(&f[2 * i + 1], &hi, 4); }
extern float g_fpr[64];
static float u2f(u32 v) { float x; memcpy(&x, &v, 4); return x; }
static u32 f2u(float x) { u32 v; memcpy(&v, &x, 4); return v; }
static double u2d(u32 hi, u32 lo) { u64 v = ((u64)hi << 32) | lo; double d; memcpy(&d, &v, 8); return d; }
static u32 d2hi(double d) { u64 v; memcpy(&v, &d, 8); return (u32)(v >> 32); }
static u32 d2lo(double d) { u64 v; memcpy(&v, &d, 8); return (u32)v; }
extern void *port_resolve(u32 guest_code_address);
extern u32 port_unresolve(u32 host_or_guest);
extern u32 port_xl(u32 guest);
extern u32 port_rc_ret(const char *name, u32 v);
extern void port_rc_enter(const char *name, u32 a0, u32 a1, u32 a2, u32 a3);
'''

def known_functions(idx):
    """guest code address -> host function name (generated functions, hand-written drafts, libultra symbols)"""
    k = {}
    names = set()
    for p in glob.glob('src/**/func_*.c', recursive=True) + glob.glob('port/nonmatching/func_*.c') + glob.glob('port/native/recomp/func_*.c'):
        for m in re.finditer(r'(func_[0-9A-F]{8})', os.path.basename(p)): names.add(m.group(1))
    names.update(n for n in idx if re.match(r'func_[0-9A-F]{8}$', n))
    for n in names: k[int(n[5:], 16)] = n
    for l in open('symbol_addrs.txt'):
        m = re.match(r'(\w+)\s*=\s*0x([0-9A-Fa-f]+);\s*//\s*type:func', l)
        if m: k.setdefault(int(m.group(2), 16) & 0x0FFFFFFF, m.group(1))
    return k

def peephole(c, known):
    """function symbols that the recompiler substituted for address constants must be declared"""
    used = set(re.findall(r'\(u32\)(func_[0-9A-F]{8}|os\w+|__os\w+|al\w+|_[A-Za-z]\w*);', c))
    kn = set(known.values())
    used |= {n for n in re.findall(r'\(u32\)([A-Za-z_]\w*);', c) if n in kn}      # any other known function name (proutSprintf, ...)
    return c, used

_INS = re.compile(r'\s*/\* [0-9A-F]+ ([0-9A-F]{8}) [0-9A-F]{8} \*/\s*(.*)$')
def _ends(text):
    """the code ends in a return or jump (among the last two instructions: a jump and its delay slot)"""
    ins = [m.group(2).strip() for m in map(_INS.match, text.split('\n')) if m]
    return not ins or any(re.match(r'(jr|j|b|eret)\b', t) or re.match(r'beq\s+\$zero,\s*\$zero', t) for t in ins[-2:])

def with_fallthrough(name, text, idx):
    """splat sometimes cuts a function in the middle: its code runs on into the next symbol (func_00449E38 continues into func_0044A100 after
    its last jal; that tail stores the player's respawn key, and the twin that returned early made every trial respawn reload map 0).  The
    following symbols' code is appended as labels of this function until it ends in a return / jump (wip/scan_fallthrough.py lists the cases)."""
    if not re.match(r'func_[0-9A-F]{8}$', name): return text
    addrs = sorted((int(n[5:], 16), n) for n, p in idx.items() if re.match(r'func_[0-9A-F]{8}$', n) and p.startswith('port'))
    last = text; prev = name
    for _ in range(6):
        if _ends(last): break
        cur = max([int(m.group(1), 16) for m in map(_INS.match, text.split('\n')) if m] or [int(name[5:], 16)])
        nxt = next((n for a, n in addrs if a > cur), None)      # the first symbol after the code already present (some files already hold the following code)
        if not nxt: break
        t = open(idx[nxt], encoding='utf-8').read()
        t = re.sub(r'^(\s*)glabel\s+' + nxt + r'\b', r'\1alabel ' + nxt, t, flags=re.M)
        t = re.sub(r'^\s*endlabel\b.*$', '', t, flags=re.M)
        text = re.sub(r'^\s*endlabel\s+' + prev + r'\b.*$', '', text, flags=re.M) + '\n' + t
        last = t; prev = nxt
    return text

def gen(names):
    os.makedirs(os.environ.get('RECOMP_OUT') or 'port/native/recomp', exist_ok=True)
    idx = m2c_fallback.asm_index()
    known = known_functions(idx)
    for _n, _p in idx.items():
        if _n.startswith('func_') and _p.startswith('port'):
            try: mips2c.ALLARGC[_n] = mips2c.int_arg_count(mips2c.parse(open(_p, encoding='utf-8').read(), _n))
            except Exception: pass
    done = []
    for name in names:
        src = idx.get(name) or idx.get(name.replace('func_00', 'func_'))
        if not src:
            print('no asm for', name); continue
        try:
            raw = open(src, encoding='utf-8').read(); ft = with_fallthrough(name, raw, idx)
            try: c = mips2c.recompile_function(ft, name, known)
            except Exception:
                if ft == raw: raise
                c = mips2c.recompile_function(raw, name, known)          # the appended code cannot be translated (hand-written libultra assembly ...): as before
        except Exception as e:
            print('FAILED', name, e); continue
        c, used = peephole(c, known)
        callee = (set(re.findall(r'\(u32 \(\*\)\(\)\)(\w+)\)\(', c)) | set(re.findall(r'\(\*\)\([^()]*\)\)(\w+)\)\(', c))) - {name}
        decls = ''.join('extern u32 %s();\n' % n for n in sorted(callee | used) if n != name and n not in ('memcpy', 'sqrtf', 'fabsf', 'sqrt', 'fabs', 'floor', 'ceil', 'rint', 'floorf', 'ceilf', 'rintf') and not n.startswith(('port_', '__builtin')))
        data = set(re.findall(r'\b(D_[0-9A-F]{8})\b', c))
        outp = (os.environ.get('RECOMP_OUT') or 'port/native/recomp') + '/%s.c' % name; newtxt = HEADER % name + decls + c + '\n'
        try: same = open(outp, newline='\n').read() == newtxt
        except OSError: same = False
        if not same: open(outp, 'w', newline='\n').write(newtxt)          # an unchanged twin keeps its mtime: build_clang.py does not recompile it
        done.append(name)
    open('port/build/rc_argc.txt', 'w').write('\n'.join('%s %d' % (n, mips2c.ARGC.get(n, 0)) for n in done if mips2c.ARGC.get(n, 0) > 0) + '\n')
    return done

if __name__ == '__main__':
    names = sys.argv[1:]
    if os.path.exists('port/recomp.txt'): names += open('port/recomp.txt').read().split()
    done = gen(sorted(set(names)))
    deny = set(open('port/m2c_deny.txt').read().split()) if os.path.exists('port/m2c_deny.txt') else set()
    deny.update(done)
    open('port/m2c_deny.txt', 'w').write('\n'.join(sorted(deny)) + '\n')
    print('recompiled:', ' '.join(done))
