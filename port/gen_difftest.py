#!/usr/bin/env python3
"""Differential test of the static recompiler: every function that has exact matching C (src/) *and* can be recompiled from its ROM
code is built twice (the C, and the recompiled MIPS as dt_<name>); port/difftest.c runs both on identical random arguments and
memory and compares results and memory.  Only leaf functions are tested (no calls), so nothing else is involved.
Outputs port/native/difftest/dt_*.c and dt_table.c (compiled by build_clang.py)."""
import glob, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mips2c, m2c_fallback, gen_recomp, fpsig

def main():
    idx = m2c_fallback.asm_index()
    known = gen_recomp.known_functions(idx)
    sigs = mips2c.fpsigs()
    man = []; srcdir = {}
    for m in ('funcs.txt', 'funcs_a.txt'):
        for l in open(m):
            f = l.split('#')[0].split()
            if len(f) >= 4 and not f[0].startswith('pad_') and f[0] in idx and os.path.exists('src/%s/%s.c' % (f[3], f[0])): man.append(f[0]); srcdir[f[0]] = f[3]
    out = 'port/native/difftest'
    os.makedirs(out, exist_ok=True)
    for p in glob.glob(out + '/*.c'): os.remove(p)
    entries = []
    for name in sorted(set(man)):
        try:
            c = mips2c.recompile_function(open(idx[name], encoding='utf-8').read(), name, known)
        except Exception:
            continue
        if re.search(r'\(u32 \(\*\)\(\)\)|\(\*\)\([^()]*\)\)\w+\)\(|port_resolve|__builtin_trap', c): continue          # not a leaf
        c = re.sub(r'\b%s(_rc)?\b' % name, lambda m: 'dt_' + m.group(0), c)
        c = c.replace('port_rc_enter("dt_%s", a0, a1, a2, a3);' % name, '')
        hdr = gen_recomp.HEADER % name
        open('%s/dt_%s.c' % (out, name), 'w', newline='\n').write(hdr + c + '\n')
        sg = sigs.get(name)
        if sg is None:                                      # return type from the matching C: void functions leave garbage in v0
            m = re.search(r'^([A-Za-z_][\w 	\*]*?)\s*\**\s*%s\s*\(' % name, open('src/%s/%s.c' % (srcdir[name], name)).read(), re.M)
            if m and m.group(1).split()[-1] == 'void' and '*' not in m.group(0).split(name)[0]: sg = ('v', ['i', 'i', 'i', 'i'])
        entries.append((name, sg))
    # the table + uniform call thunks
    t = ['/* generated by port/gen_difftest.py */', 'typedef unsigned int u32; typedef unsigned long long u64; typedef signed int s32;']
    for name, sg in entries:
        t.append('extern u32 %s(); extern u32 dt_%s();' % (name, name))
    t.append('static float u2f(u32 v) { union { u32 u; float f; } x; x.u = v; return x.f; }')
    t.append('static u32 f2u(float f) { union { u32 u; float f; } x; x.f = f; return x.u; }')
    t.append('u64 dt_call(int idx, int which, const u32 *a) {')
    t.append('    switch (idx) {')
    for i, (name, sg) in enumerate(entries):
        for which, fn in ((0, name), (1, 'dt_' + name)):
            if sg:
                rt, types = sg
                if '?' in types or rt == 'l': args = None
                else:
                    ps = []
                    for k, ty in enumerate(types):
                        ps.append({'i': 'a[%d]' % k, 'f': 'u2f(a[%d])' % k, 'd': '0.0'}[ty])
                    proto = '%s (*)(%s)' % ({'f': 'float', 'd': 'double', 'v': 'void', 'i': 'u32'}[rt], ', '.join({'i': 'u32', 'f': 'float', 'd': 'double'}[x] for x in types) or 'void')
                    call = '((%s)%s)(%s)' % (proto, fn, ', '.join(ps))
                    if rt == 'f': t.append('    case %d: if (which == %d) return f2u(%s); break;' % (i * 2 + which, which, call))
                    elif rt == 'v': t.append('    case %d: if (which == %d) { %s; return 0; } break;' % (i * 2 + which, which, call))
                    else: t.append('    case %d: if (which == %d) return (u32)%s; break;' % (i * 2 + which, which, call))
                    continue
            t.append('    case %d: if (which == %d) return (u32)((u32 (*)(u32, u32, u32, u32))%s)(a[0], a[1], a[2], a[3]); break;' % (i * 2 + which, which, fn))
    t.append('    }\n    return 0;\n}')
    t.append('int dt_count = %d;' % len(entries))
    sigs_txt = []
    for name, sg in entries:
        sigs_txt.append('"%s:%s"' % ({'f': 'f', 'd': 'd', 'v': 'v', 'i': 'i', 'l': 'i'}[sg[0]] if sg else 'i', ''.join(sg[1]) if sg else 'iiii'))
    t.append('const char *dt_sigs[] = { %s };' % ', '.join(sigs_txt))
    t.append('const char *dt_names[] = { %s };' % ', '.join('"%s"' % n for n, _ in entries))
    open(out + '/dt_table.c', 'w', newline='\n').write('\n'.join(t) + '\n')
    print('difftest functions:', len(entries))

if __name__ == '__main__':
    main()
