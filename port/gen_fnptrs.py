#!/usr/bin/env python3
"""Generate port/gen/fnptrs.c: table (guest code address -> host function) for every function in docs/game_funcs.txt."""
import os, re
names = []
for l in open('docs/game_funcs.txt'):
    if l.startswith('#'): continue
    f = l.split()
    if len(f) >= 2 and re.fullmatch(r'func_[0-9A-F]{8}', f[1]): names.append(f[1])
os.makedirs('port/gen', exist_ok=True)
with open('port/gen/fnptrs.c', 'w') as o:
    o.write('/* generated by port/gen_fnptrs.py */\n')
    for n in names: o.write(f'extern void {n}();\n')
    o.write('struct port_fn { unsigned guest; void *host; };\nstruct port_fn port_fn_table[] = {\n')
    for n in names: o.write(f'    {{ 0x{n[5:]}u, (void *){n} }},\n')
    o.write(f'}};\nint port_fn_count = {len(names)};\n')
print(len(names), 'functions in the pointer table')
