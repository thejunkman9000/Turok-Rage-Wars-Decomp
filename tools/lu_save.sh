#!/usr/bin/env bash
# Save libultra match results (gcc 2.8.1 -O2) into docs/libultra_matches.txt
SRCS="osSendMesg.c osRecvMesg.c osJamMesg.c osCreateMesgQueue.c osSetThreadPri.c osStartThread.c osCreateThread.c osDestroyThread.c osSetEventMesg.c osVirtualToPhysical.c osTimer.c osSetTimer.c osGetThreadPri.c osViSwapBuffer.c osViSetMode.c osViBlack.c osSpTaskYield.c __osViSwapContext.c osAiSetFrequency.c osViSetEvent.c osGetTime.c osPiStartDma.c osPiRawStartDma.c osSpTaskLoadGo.c"
{
  echo "# libultra functions located in the ROM by compiling libreultra C with gcc 2.8.1 -O2 and searching"
  echo "# (relocated words masked). 'EXACT' = byte-identical modulo relocations; N/M = best partial alignment."
  echo "# Generated by tools/lu_save.sh. Note partial scores understate closeness when a delay-slot fill shifts the tail."
  python3 tools/lu_match.py 2.8.1 -O2 -- $SRCS | awk '$2+0>=8 && $1 !~ /^D_/' | sort -t'x' -k2
} > docs/libultra_matches.txt
cat docs/libultra_matches.txt
